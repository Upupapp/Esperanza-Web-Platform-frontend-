// Writes resources/js/lucide-icons.js: the Lucide icons this site names.
//
//   node scripts/lucide-icons.mjs
//
// app.js used to hand createIcons() all ~1,700 icons, which were most of the
// initial JavaScript (the 150 KB budget, 2026-10-08). Every quoted kebab-case
// word in the views, scripts, config and data that is an icon's name is kept;
// an icon named only at run time (by a record from the API) is drawn from the
// full set, which app.js fetches once when a page asks for one it lacks.
// LucideIconsTest fails when a view names an icon this list does not have:
// run this script again.
import * as lucide from 'lucide';
import fs from 'node:fs';
import path from 'node:path';

const roots = ['resources/views', 'resources/js', 'resources/data', 'config'];
const out = 'resources/js/lucide-icons.js';
const files = [];
const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) walk(full);
        else if (/\.(php|js|mjs)$/.test(entry.name) && path.resolve(full) !== path.resolve(out)) files.push(full);
    }
};
roots.filter((r) => fs.existsSync(r)).forEach(walk);

const pascal = (name) => name.split('-').map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join('');
const names = new Set();
for (const file of files) {
    const text = fs.readFileSync(file, 'utf8');
    for (const match of text.matchAll(/['"`]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)['"`]/g)) {
        const key = pascal(match[1]);
        if (lucide.icons[key]) names.add(key);
    }
}
const sorted = [...names].sort();
fs.writeFileSync(out, [
    '// Generated by scripts/lucide-icons.mjs: the Lucide icons this site names.',
    '// Do not edit by hand; run `node scripts/lucide-icons.mjs` after naming a new icon.',
    `import {\n${sorted.map((n) => `    ${n},`).join('\n')}\n} from 'lucide';`,
    '',
    `export default {\n${sorted.map((n) => `    ${n},`).join('\n')}\n};`,
    '',
].join('\n'));
console.log(`${sorted.length} of ${Object.keys(lucide.icons).length} icons -> ${out}`);
